#creamos el arreglo del inventario
inventario = [
    ["A001", "Teclado", 10, 20],
    ["A002", "Mouse", 15, 15],
    ["A003", "Monitor", 5, 12],
    ["A004", "Impresora", 8, 10],
    ["A005", "Parlantes", 25, 20]
]

#funcion para calcular el pedido recibe 2 parametros
def calcular_pedido(stock_actual, stock_minimo):

    if stock_actual < stock_minimo:
        return stock_minimo - stock_actual
    else:
        return 0

print("REPORTE DE REABASTECIMIENTO")
print("-" * 40)
#recorremos la matriz
for articulo in inventario:

    nombre = articulo[1]
    stock_actual = articulo[2]
    stock_minimo = articulo[3]
#llenamos los parametros de la funcion y la llamams
    cantidad_pedir = calcular_pedido(
        stock_actual,
        stock_minimo
    )

    print("Artículo:", nombre)
    print("Cantidad a pedir:", cantidad_pedir)
    print("-" * 40)